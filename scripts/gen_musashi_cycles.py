#!/usr/bin/env python3
"""Writes src/m68k/musashi_cycles.h, the 68000 column of MAME's Musashi
opcode table (m68kops.cpp's m68k_opcode_table: match, mask and cycles per
CPU type), for the boards whose MAME driver runs its 68000s on the Musashi
core (m68000msh_device: the Y Board).

  gen_musashi_cycles.py MAME/src/devices/cpu/m68000/m68kops.cpp src/m68k/musashi_cycles.h

The table is built the way m68ki_build_opcode_table builds m68ki_cycles[0]:
each entry sets every opcode that matches it on its mask bits, later
entries over earlier ones; opcodes no entry sets are 0.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src).read()
start = text.index("m68k_opcode_table[] =")
rows = re.findall(r"\{ 0x([0-9a-f]{4}), 0x([0-9a-f]{4}), \{\s*([0-9]+),", text[start:])
entries = [(int(m, 16), int(k, 16), int(c)) for m, k, c in rows if int(c) != 255]
with open(out, "w") as f:
    f.write("// Generated by scripts/gen_musashi_cycles.py from MAME's\n")
    f.write("// src/devices/cpu/m68000/m68kops.cpp (license:BSD-3-Clause,\n")
    f.write("// copyright-holders Karl Stenerud): the 68000 column of the Musashi\n")
    f.write("// opcode table, {match, mask, cycles}. Do not edit.\n")
    f.write("#pragma once\n\n#include <array>\n#include <cstdint>\n\nnamespace m68k {\n\n")
    f.write("struct MusashiCycEntry { uint16_t match, mask; uint8_t cycles; };\n")
    f.write("inline constexpr MusashiCycEntry kMusashiCycEntries[] = {\n")
    for m, k, c in entries:
        f.write(f"    {{0x{m:04x}, 0x{k:04x}, {c}}},\n")
    f.write("};\n\n")
    f.write("// m68ki_cycles[0]: the base cycles of each opcode word (MAME's\n")
    f.write("// m68ki_build_opcode_table)\n")
    f.write("inline const std::array<uint8_t, 0x10000> &musashi_cycles() {\n")
    f.write("    static const std::array<uint8_t, 0x10000> t = [] {\n")
    f.write("        std::array<uint8_t, 0x10000> a{};\n")
    f.write("        for (const MusashiCycEntry &e : kMusashiCycEntries) {\n")
    f.write("            uint16_t extra = 0;\n")
    f.write("            do {\n")
    f.write("                a[uint16_t(e.match | extra)] = e.cycles;\n")
    f.write("                extra = uint16_t(((extra | e.mask) + 1) & ~e.mask);\n")
    f.write("            } while (extra);\n")
    f.write("        }\n")
    f.write("        return a;\n")
    f.write("    }();\n")
    f.write("    return t;\n")
    f.write("}\n\n} // namespace m68k\n")
print(f"{len(entries)} entries")
