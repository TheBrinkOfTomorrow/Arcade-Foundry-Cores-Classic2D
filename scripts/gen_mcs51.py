def funcs(text, names):
    res = []
    for n in names:
        m = re.search(r'\n((?:u8|void|offs_t|bool) mcs51_cpu_device::' + n + r'\([^)]*\)\s*\n\{)', text)
        assert m, n
        s = m.start(1)
        e = text.index('\n}\n', s) + 3
        res.append(text[s:e])
    return '\n'.join(res)

sfrnames = ['psw_r','psw_w','acc_r','b_r','b_w','sp_r','sp_w','dptr_r','dptr_w','pcon_r','pcon_w','tcon_r','tcon_w','tmod_r','tmod_w','scon_r','scon_w','sbuf_r','sbuf_w','ie_r','ie_w','ip_r','ip_w','p0_r','p0_w','p1_r','p1_w','p2_r','p2_w','p3_r','p3_w','tl0_r','tl0_w','tl1_r','tl1_w','th0_r','th0_w','th1_r','th1_w']
corenames = ['clear_current_irq','external_ram_iaddr','transmit','handle_8bit_uart_clock','transmit_receive','update_timer_t0','update_timer_t1','update_timer_t2','update_irq_prio','irqs_complete_and_mask','manage_idle_on_interrupt','check_irqs','burn_cycles','handle_irq','execute_set_input','handle_ta_window','execute_run','device_reset']
