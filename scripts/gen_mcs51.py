def enum_block(name_first):
    i = h.index(name_first); s = h.rindex('enum {', 0, i); e = h.index('};', i) + 2
    return h[s:e]
enums = '\n'.join('\t' + enum_block(n) for n in ['PSW_CY =', 'IE_A  =', 'IP_T2 =', 'TCON_TF1 =', 'SCON_SM0 =', 'TMOD_GATE1 =', 'PCON_SMOD ='])
s = h.index('\tvoid acall(u8 r);'); e = h.index('};', s)
opdecls = h[s:e]
s = h.index('\tu8 psw_r();'); e = h.index('\tvoid transmit(int state);')
